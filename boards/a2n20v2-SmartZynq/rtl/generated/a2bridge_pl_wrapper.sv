`timescale 1ns/1ps

// Smart-Zynq implementation of the external A2N20v2 a2bridge CPLD.
//
// All FPGA-internal buses are unidirectional.  Open-collector Apple
// lines are expressed as pull-low intent outputs; the parent combines
// those with PHY sense using ordinary AND gates.
//
// bridge_rd and bridge_wr retain the legacy wrapper names, but electrically
// they are active LOW.  They correspond to upstream:
//   a2_bridge_rd_n_o
//   a2_bridge_wr_n_o
//
// Selector map used by upstream apple_bus.sv:
//
//   0 = bus control/status
//   1 = Apple data bus
//   2 = address A[7:0]
//   3 = address A[15:8]
//   4 = M2B0 / M2SEL
//   5 = DIP switches
//
module a2bridge_pl_wrapper(
    input  wire        clk,
    input  wire        reset_n,
    input  wire [3:0]  switch_n,

    input  wire [15:0] bus_addr,
    input  wire [7:0]  bus_data,
    output wire [7:0]  bus_data_out,

    input  wire        bus_rw,
    input  wire        bus_sync,
    input  wire        bus_7m,
    input  wire        bus_q3,
    input  wire        bus_phi0,
    input  wire        bus_phi1,

    input  wire        bus_iosel_n,
    input  wire        bus_iostrb_n,
    input  wire        bus_devsel_n,

    input  wire        bus_reset_n,

    input  wire        bus_m2sel,
    input  wire        bus_m2b0,

    input  wire        bus_rdy_n,
    input  wire        bus_dma_n,
    input  wire        bus_irq_n,
    input  wire        bus_nmi_n,
    input  wire        bus_inh_n,

    // Active-high: drive the corresponding NPN open-collector stage.
    output wire        pull_inh,
    output wire        pull_irq,
    output wire        pull_rdy,
    output wire        pull_dma,
    output wire        pull_nmi,
    output wire        pull_reset,

    input  wire        bus_dmain_n,
    input  wire        bus_intin_n,
    output wire        bus_dmaout_n,
    output wire        bus_intout_n,

    input  wire [7:0]  bridge_data_i,
    output wire [7:0]  bridge_data_o,
    input  wire [2:0]  bridge_sel,

    // ACTIVE LOW despite the historical signal names.
    input  wire        bridge_rd,
    input  wire        bridge_wr,

    output wire        bridge_phi1,
    output wire        bridge_7m,
    output wire        bridge_q3,
    output wire        bridge_reset_n,

    // Smart-Zynq never drives the Apple address bus, so addr OE is observed
    // but intentionally unused.
    input  wire        bridge_addr_oe_n,

    // Low means the A2FPGA core wants its latched data driven onto D[7:0].
    input  wire        bridge_data_oe_n
);

    reg [7:0] bus_data_latch;
    reg [7:0] control_latch;
    reg       bridge_wr_q;

    reg [7:0] bridge_read_data;

    /*
     * FPGA -> bridge read path.
     *
     * apple_bus.sv asserts bridge_rd low, selects a register,
     * then samples bridge_data_o.
     */
    always @* begin
        case (bridge_sel)
            3'd0:
                bridge_read_data = {
                    1'b1,
                    bus_reset_n,
                    bus_nmi_n,
                    bus_dma_n,
                    bus_rdy_n,
                    bus_irq_n,
                    bus_inh_n,
                    bus_rw
                };

            3'd1:
                bridge_read_data = bus_data;

            3'd2:
                bridge_read_data = bus_addr[7:0];

            3'd3:
                bridge_read_data = bus_addr[15:8];

            3'd4:
                bridge_read_data = {
                    6'b111111,
                    bus_m2sel,
                    bus_m2b0
                };

            3'd5:
                bridge_read_data = {
                    4'hf,
                    switch_n
                };

            default:
                bridge_read_data = 8'hff;
        endcase
    end

    // Always drive the core-side read mux.  apple_bus samples this only
    // while it is not writing (a2_bridge_d_oe_o = 0).
    assign bridge_data_o = bridge_read_data;

    /*
     * Capture writes generated by apple_bus.sv.
     *
     * Do not use bridge_wr itself as a derived FPGA clock.  Detect its falling
     * edge in the 54-MHz logic clock domain instead.
     */
    always @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            bridge_wr_q   <= 1'b1;
            bus_data_latch <= 8'h00;
            control_latch <= 8'hff;
        end else begin
            bridge_wr_q <= bridge_wr;

            if (bridge_wr_q && !bridge_wr) begin
                case (bridge_sel)
                    // GPIO/control output register.
                    3'd0:
                        control_latch <= bridge_data_i;

                    // Apple D[7:0] output latch.
                    3'd1:
                        bus_data_latch <= bridge_data_i;

                    default: begin
                    end
                endcase
            end
        end
    end

    /*
     * Apple data-bus output.
     *
     * apple_bus.sv controls bridge_data_oe_n independently of the short
     * selector-1 write pulse.  Therefore selector-1 data must be latched.
     * Direction/OE for the external U5 transceiver is handled by the PHY.
     */
    assign bus_data_out = bus_data_latch;

    /*
     * Shared Apple lines are open collector on the proto-card NPNs.
     *
     * control_latch bit assignments match control_in_r/control_out_r in
     * upstream apple_bus.sv:
     *
     *   bit 1 = /INH
     *   bit 2 = /IRQ
     *   bit 3 = /RDY
     *   bit 4 = /DMA
     *   bit 5 = /NMI
     *   bit 6 = /RESET
     *
     * A 0 in the latch means "assert the Apple line low".
     */
    assign pull_inh   = ~control_latch[1];
    assign pull_irq   = ~control_latch[2];
    assign pull_rdy   = ~control_latch[3];
    assign pull_dma   = ~control_latch[4];
    assign pull_nmi   = ~control_latch[5];
    assign pull_reset = ~control_latch[6];

    // Apple timing signals passed directly to the FPGA-side core.
    assign bridge_phi1    = bus_phi1;
    assign bridge_7m      = bus_7m;
    assign bridge_q3      = bus_q3;
    assign bridge_reset_n = bus_reset_n;

    // Original Apple daisy-chain pins are NC on this Smart-Zynq adapter,
    // but preserve harmless pass-through semantics.
    assign bus_dmaout_n = bus_dmain_n;
    assign bus_intout_n = bus_intin_n;

    // Explicitly mark unused physical-bus inputs for readability.
    wire _unused_ok;
    assign _unused_ok =
        bus_sync       ^
        bus_phi0       ^
        bus_iosel_n    ^
        bus_iostrb_n   ^
        bus_devsel_n   ^
        bridge_rd      ^
        bridge_data_oe_n ^
        bridge_addr_oe_n;

endmodule
